"""DEV-ONLY generator. Writes ../../data/doctor_ids.py with the known-BAD
PersistenceIDs for the Save doctor: the exact junk each builder rejects
(unregistered / dev / deleted / AlwaysCook assets whose ids the game's
strict-mode load refuses — a single one in the save aborts the character
load).

Sources, reusing each builder's own classification against the static dumps
(ItemDumper_*.jsonl from `tools/icon_extractor --dump-data`):
- pickups:   ItemDumper_items.jsonl records where build_pickup_ids.breaks_load
- recipes:   ItemDumper_recipes.jsonl records where build_recipe_ids.is_junk
             and not in the embedded good set
- buildings: ItemDumper_buildings.jsonl records where build_building_ids.is_junk
             and not in the embedded good set

Run after regenerating the dumps AND the good sets (build_recipe_ids /
build_building_ids / build_pickup_ids) so blocklists stay disjoint from
them. The generated data/doctor_ids.py ships in the app; this generator
does not.
"""
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, ROOT)


def _load(name):
    spec = importlib.util.spec_from_file_location(
        name, os.path.join(HERE, name + ".py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _records(path):
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                yield json.loads(line)
            except json.JSONDecodeError:
                continue


def bad_pickup_ids():
    # breaks_load, not keep_record: broken-name items ([PH]/dangling names)
    # are excluded from the unlocker but are registered and harmless in a
    # save - the doctor must never remove them.
    b = _load("build_pickup_ids")
    src = os.path.join(HERE, "ItemDumper_items.jsonl")
    bad = []
    for rec in _records(src):
        pid = rec.get("PersistenceID")
        if pid and b.breaks_load(rec):
            bad.append(pid)
    return sorted(set(bad))


def _bad_by_is_junk(builder_name, dump, good_ids):
    b = _load(builder_name)
    src = os.path.join(HERE, dump)
    bad = set()
    for rec in _records(src):
        pid = rec.get("PersistenceID")
        if not pid or pid in good_ids:
            continue
        if b.is_junk(rec):
            bad.add(pid)
    return sorted(bad)


def main():
    from data.unlock_ids import EMBEDDED_RECIPE_IDS, EMBEDDED_BUILDING_IDS

    pickups = bad_pickup_ids()
    recipes = _bad_by_is_junk("build_recipe_ids", "ItemDumper_recipes.jsonl",
                              set(EMBEDDED_RECIPE_IDS))
    buildings = _bad_by_is_junk("build_building_ids",
                                "ItemDumper_buildings.jsonl",
                                set(EMBEDDED_BUILDING_IDS))
    dst = os.path.join(ROOT, "data", "doctor_ids.py")
    with open(dst, "w", encoding="utf-8") as f:
        f.write('"""GENERATED by tools/game_dump/build_doctor_ids.py - '
                'do not edit by hand.\n')
        f.write("Known-BAD PersistenceIDs (dev/test/deleted assets) that "
                "break the strict\nsave load if present in the matching "
                "unlock list. Used by the Save doctor.\n")
        f.write('"""\n')
        for name, ids in (("BAD_PICKUP_IDS", pickups),
                          ("BAD_RECIPE_IDS", recipes),
                          ("BAD_BUILDING_IDS", buildings)):
            f.write("\n%s = [\n" % name)
            for pid in ids:
                f.write("    %r,\n" % (pid,))
            f.write("]\n")
    print("pickups: %d bad, recipes: %d bad, buildings: %d bad -> %s"
          % (len(pickups), len(recipes), len(buildings), dst))


if __name__ == "__main__":
    main()
