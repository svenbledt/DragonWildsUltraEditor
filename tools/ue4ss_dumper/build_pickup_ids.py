"""DEV-ONLY generator. Reads ItemDumper_items.jsonl and writes ../../data/pickup_ids.py
with EMBEDDED_ITEM_PICKUP_IDS: every real, obtainable item PersistenceID, so the
Picked-Up Items unlocker can fill Progress.ItemsPickedUp without tripping the
save's strict-mode validation. Run after regenerating the item dump. Not shipped.
"""
import argparse
import json
import os
import sys

BAD_FOLDERS = ("/Deleted/", "/Dev/", "/Test/", "/Debug/")


def item_name(rec):
    return rec.get("SourceString") or rec.get("DisplayName") or rec.get("Name") or ""


def keep_record(rec):
    """True if `rec` is a real, obtainable item safe to add to ItemsPickedUp."""
    if not rec.get("PersistenceID"):
        return False
    full = rec.get("__fullname", "") or ""
    if any(bad in full for bad in BAD_FOLDERS):
        return False
    name = item_name(rec)
    if "[PH]" in name or "(Expired)" in name or name.strip() == "":
        return False
    return True


def build_ids(records):
    """Filtered, de-duplicated PersistenceIDs in first-seen order."""
    out, seen = [], set()
    for rec in records:
        if keep_record(rec):
            pid = rec["PersistenceID"]
            if pid not in seen:
                seen.add(pid)
                out.append(pid)
    return out


def load_records(path):
    records = []
    with open(path, "r", encoding="utf-8") as f:
        for lineno, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                records.append(json.loads(line))
            except json.JSONDecodeError as e:
                raise ValueError(f"{path}: malformed JSON on line {lineno}: {e}") from e
    return records


def write_module(ids, path):
    with open(path, "w", encoding="utf-8") as f:
        f.write('"""GENERATED by tools/ue4ss_dumper/build_pickup_ids.py - do not edit by hand.\n')
        f.write('Real, obtainable item PersistenceIDs for the Picked-Up Items unlocker.\n')
        f.write('"""\n\n')
        f.write("EMBEDDED_ITEM_PICKUP_IDS = [\n")
        for pid in ids:
            f.write("    %r,\n" % (pid,))
        f.write("]\n")


def load_current_count(path):
    """Count EMBEDDED_ITEM_PICKUP_IDS in an existing pickup_ids.py (0 if absent)."""
    if not os.path.exists(path):
        return 0
    ns = {}
    try:
        with open(path, "r", encoding="utf-8") as f:
            exec(compile(f.read(), path, "exec"), ns)  # noqa: S102 (trusted generated file)
    except (OSError, SyntaxError):
        return 0
    return len(ns.get("EMBEDDED_ITEM_PICKUP_IDS", []))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true",
                    help="analyze only, do not write")
    args = ap.parse_args()

    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(os.path.dirname(here))
    src = os.path.join(here, "ItemDumper_items.jsonl")
    dst = os.path.join(root, "data", "pickup_ids.py")
    if not os.path.exists(src):
        print("ERROR: %s not found. Run the F8 item dump first." % src)
        sys.exit(1)

    print("Reading item dump: %s" % src)
    records = load_records(src)
    print("Records in dump: %d" % len(records))
    ids = build_ids(records)
    current = load_current_count(dst)
    print("Pickup ids (real, obtainable): %d" % len(ids))
    print("Current pickup_ids.py entries: %d" % current)
    print("  net change: %+d" % (len(ids) - current))

    if args.dry_run:
        print("\n--dry-run: not writing. Re-run without --dry-run to apply.")
        return
    write_module(ids, dst)
    print("wrote %d ids -> %s" % (len(ids), dst))


if __name__ == "__main__":
    main()
