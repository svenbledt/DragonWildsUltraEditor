_HEX = set(string.hexdigits.upper())


def is_hex_guid(s):
    """True for a 32-char uppercase-hex FGuid (the ShrinesUnlocked format)."""
    return isinstance(s, str) and len(s) == 32 and all(c in _HEX for c in s)


def build_ids(records):
    """Union KNOWN_SHRINE_IDS with any valid hex PersistenceIDs from the dump.

    Non-hex ids (e.g. base64 data-asset PIDs) are rejected. Order-stable,
    deduped, known ids first.
    """
    out, seen = [], set()
    for g in KNOWN_SHRINE_IDS:
        if g not in seen:
            seen.add(g)
            out.append(g)
    for rec in records:
        pid = rec.get("PersistenceID")
        if is_hex_guid(pid) and pid not in seen:
            seen.add(pid)
            out.append(pid)
    return out


def validate(ids):
    """Return the list of KNOWN_SHRINE_IDS missing from `ids` (empty == good)."""
    have = set(ids)
    return [g for g in KNOWN_SHRINE_IDS if g not in have]


def load_records(path):
    if not os.path.exists(path):
        return []
    records = []
    with open(path, "r", encoding="utf-8") as f:
        for lineno, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                records.append(json.loads(line))
            except json.JSONDecodeError as e:
                raise ValueError(f"{path}: malformed JSON on line {lineno}: {e}") from e
    return records


def write_module(ids, path):
    with open(path, "w", encoding="utf-8") as f:
        f.write('"""GENERATED by ue4ss_dumper/build_shrine_ids.py - do not edit by hand.\n')
        f.write('Sanguine Urn / lifepool-shrine GUIDs for Progress.ShrinesUnlocked.\n')
        f.write('"""\n\n')
        f.write("EMBEDDED_SHRINE_IDS = [\n")
        for g in ids:
            f.write("    %r,\n" % (g,))
        f.write("]\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true",
                    help="analyze only, do not write")
    args = ap.parse_args()

    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(here, "ItemDumper_urns.jsonl")
    dst = os.path.join(os.path.dirname(here), "shrine_ids.py")
    records = load_records(src)
    if not records:
        # Missing OR empty: no accumulated shrine ids yet. Urns are in-world level
        # actors (BP_HealthShrine_C); the in-game F6/F8 accumulator writes their
        # real UniqueShrineIdentifier GUIDs here as you roam past them. Run it
        # across every region to build the complete set, then re-run this script.
        state = "empty" if os.path.exists(src) else "absent"
        print("Urn accumulator file is %s - roam the map pressing F6 (dump_shrines) "
              "to collect BP_HealthShrine_C UniqueShrineIdentifier GUIDs into %s. "
              "Using the known set for now." % (state, os.path.basename(src)))
    ids = build_ids(records)
    missing = validate(ids)
    if missing:
        print("WARNING: known shrine GUIDs missing from build:", missing)
    contributed = len(ids) - len(KNOWN_SHRINE_IDS)
    hex_records = sum(1 for r in records if is_hex_guid(r.get("PersistenceID")))
    if records and hex_records == 0:
        # The file had records but none in ShrinesUnlocked's hex-GUID format:
        # the scan reached assets, but their PIDs are the wrong kind.
        print("WARNING: urn dump had records but 0 valid hex GUIDs - their "
              "PIDs are not ShrinesUnlocked-format. Shipping known set only; "
              "consider the in-world actor-sweep fallback.")
    print("shrine ids: %d known + %d from dump = %d total"
          % (len(KNOWN_SHRINE_IDS), contributed, len(ids)))
    if args.dry_run:
        print("\n--dry-run: not writing. Re-run without --dry-run to apply.")
        return
    write_module(ids, dst)
    print("wrote %d shrine ids -> %s" % (len(ids), dst))


if __name__ == "__main__":
    main()
