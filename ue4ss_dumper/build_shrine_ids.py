"""DEV-ONLY generator. Builds ../shrine_ids.py (EMBEDDED_SHRINE_IDS) for the
Sanguine Urn unlocker, which fills Progress.ShrinesUnlocked (each entry expands
max HP by 10, derived at load). Urn ids are 32-char uppercase hex FGuids.

Reads ItemDumper_urns.jsonl if present (from the extended dumper) and UNIONS its
valid hex ids with KNOWN_SHRINE_IDS (harvested from real saves). Validates that
every known id survives, and warns loudly if the dump contributed nothing new
(a sign the data-asset scan did not reach the real urn ids). Not shipped.
"""
import argparse
import json
import os
import string

# GUIDs confirmed present in real saves' Progress.ShrinesUnlocked (7 distinct:
# Cpt. Trojan had all 7 at 170 HP; Zalacar had 3 of them at 130 HP).
KNOWN_SHRINE_IDS = [
    "824A3798412A1067890E86A2AEB609FF",
    "DB621D2A40316F7B97255696742C2AA1",
    "7DE4A84C4997053BD7171089B408AE13",
    "485514AA4D440FC3EBF331B6F5128ECE",
    "DCF55CC14E4019584B5B03AB1D1ECC75",
    "13A95FDF40A30E7465E66C96CAA63778",
    "BA041CF14868F751575411B22EFE218A",
]

_HEX = set(string.hexdigits.upper())


def is_hex_guid(s):
    """True for a 32-char uppercase-hex FGuid (the ShrinesUnlocked format)."""
    return isinstance(s, str) and len(s) == 32 and all(c in _HEX for c in s)


def build_ids(records):
    """Union KNOWN_SHRINE_IDS with any valid hex PersistenceIDs from the dump.

    Non-hex ids (e.g. base64 data-asset PIDs) are rejected. Order-stable,
    deduped, known ids first.
    """
    out, seen = [], set()
    for g in KNOWN_SHRINE_IDS:
        if g not in seen:
            seen.add(g)
            out.append(g)
    for rec in records:
        pid = rec.get("PersistenceID")
        if is_hex_guid(pid) and pid not in seen:
            seen.add(pid)
            out.append(pid)
    return out


def validate(ids):
    """Return the list of KNOWN_SHRINE_IDS missing from `ids` (empty == good)."""
    have = set(ids)
    return [g for g in KNOWN_SHRINE_IDS if g not in have]


def load_records(path):
    if not os.path.exists(path):
        return []
    records = []
    with open(path, "r", encoding="utf-8") as f:
        for lineno, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                records.append(json.loads(line))
            except json.JSONDecodeError as e:
                raise ValueError(f"{path}: malformed JSON on line {lineno}: {e}") from e
    return records


def write_module(ids, path):
    with open(path, "w", encoding="utf-8") as f:
        f.write('"""GENERATED by ue4ss_dumper/build_shrine_ids.py - do not edit by hand.\n')
        f.write('Sanguine Urn / lifepool-shrine GUIDs for Progress.ShrinesUnlocked.\n')
        f.write('"""\n\n')
        f.write("EMBEDDED_SHRINE_IDS = [\n")
        for g in ids:
            f.write("    %r,\n" % (g,))
        f.write("]\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true",
                    help="analyze only, do not write")
    args = ap.parse_args()

    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(here, "ItemDumper_urns.jsonl")
    dst = os.path.join(os.path.dirname(here), "shrine_ids.py")
    records = load_records(src)
    if not records:
        # Missing OR empty (0-byte placeholder): the data-asset scan produced
        # no urn records at all - the expected result, since Sanguine urns are
        # in-world actors, not data-assets.
        state = "empty" if os.path.exists(src) else "absent"
        print("Urn dump is %s - Sanguine urns are in-world actors, not "
              "data-assets, so the F8 data-asset dump does not emit them. "
              "Using the known set harvested from real saves." % state)
    ids = build_ids(records)
    missing = validate(ids)
    if missing:
        print("WARNING: known shrine GUIDs missing from build:", missing)
    contributed = len(ids) - len(KNOWN_SHRINE_IDS)
    if records and contributed == 0:
        # The file had records but none in ShrinesUnlocked's hex-GUID format:
        # the scan reached assets, but their PIDs are the wrong kind.
        print("WARNING: urn dump had records but 0 valid hex GUIDs - their "
              "PIDs are not ShrinesUnlocked-format. Shipping known set only; "
              "consider the in-world actor-sweep fallback.")
    print("shrine ids: %d known + %d from dump = %d total"
          % (len(KNOWN_SHRINE_IDS), contributed, len(ids)))
    if args.dry_run:
        print("\n--dry-run: not writing. Re-run without --dry-run to apply.")
        return
    write_module(ids, dst)
    print("wrote %d shrine ids -> %s" % (len(ids), dst))


if __name__ == "__main__":
    main()
